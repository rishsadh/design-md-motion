// Writes docs/RULES.md from the rule table, so the docs cannot drift from the code.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { RULES, DEFAULTS } from '../src/rules.mjs';

export function rulesMarkdown() {
  const out = ['# Rules', '', 'Generated by `node scripts/gen-rules-doc.mjs`. Do not edit by hand.', '',
    `Defaults: reduced-motion check above ${DEFAULTS.reduceThresholdMs}ms, transition ceiling ${DEFAULTS.maxTransitionMs}ms, spring settle limit ${DEFAULTS.maxSpringSettleMs}ms, bleed range ${DEFAULTS.minBleedMm}mm to ${DEFAULTS.maxBleedMm}mm.`, '',
    '| Rule | Default | What it checks |', '|---|---|---|'];
  for (const r of RULES) out.push(`| \`${r.id}\` | ${r.severity} | ${r.summary} |`);
  out.push('');
  for (const r of RULES) out.push(`## ${r.id}`, '', `Default severity: ${r.severity}.`, '', r.summary, '', `Why: ${r.why}`, '');
  return out.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.writeFileSync(new URL('../docs/RULES.md', import.meta.url), rulesMarkdown());
  console.log('wrote docs/RULES.md');
}
