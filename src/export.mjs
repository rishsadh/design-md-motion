// Export resolved motion tokens to CSS custom properties or W3C DTCG JSON.
import { isPlainObject, fmt } from './units.mjs';
import { effectiveIntent, parseReduced, resolveSlot } from './motion.mjs';
import { springToLinear, KEYWORD_BEZIER } from './easing.mjs';

const css = (n) => `${fmt(n)}ms`;
const easeOut = `cubic-bezier(${KEYWORD_BEZIER['ease-out'].join(', ')})`;

function easingCss(e) {
  return e.css;
}

/** Build a flat description of everything exportable, resolved. */
export function resolveAll(model, fm) {
  const out = { durations: {}, easings: {}, springs: {}, loops: {}, intents: {}, reduced: null, timeConstants: {} };
  for (const t of model.durations) if (t.ms !== null) out.durations[t.name] = t.ms;
  for (const t of model.timeConstants) if (t.ms !== null) out.timeConstants[t.name] = t.ms;
  for (const t of model.easings) if (!t.parsed.error) out.easings[t.name] = t.parsed;
  for (const t of model.springs) {
    if (t.parsed.error) continue;
    const lin = springToLinear(t.parsed);
    out.springs[t.name] = { ...t.parsed, derived: t.derived, linear: lin.css, settleMs: lin.durationMs };
  }
  if (model.reduced && !model.reduced.shapeError) {
    out.reduced = { default: model.reduced.default ?? null, durationMs: model.reduced.durationMs };
  }
  for (const lp of model.loops) {
    if (!isPlainObject(lp.raw)) continue;
    const period = lp.raw.period === undefined ? null : resolveSlot(model, fm, 'duration', lp.raw.period);
    const easing = lp.raw.easing === undefined ? null : resolveSlot(model, fm, 'easing', lp.raw.easing);
    out.loops[lp.name] = {
      periodMs: period && period.ok ? period.ms : null,
      easing: easing && easing.ok ? easing.easing : null,
      reduced: lp.raw.reduced ?? null,
      periodRef: period && period.ok && period.token ? `${period.group}.${period.token.name}` : null,
      easingRef: easing && easing.ok && easing.token ? easing.token.name : null,
    };
  }
  for (const it of model.intents) {
    if (!isPlainObject(it.raw)) continue;
    const e = effectiveIntent(model, fm, it);
    const slot = (k) => (e.slots[k] && e.slots[k].ok && e.slots[k].token ? `${e.slots[k].group}.${e.slots[k].token.name}` : null);
    out.intents[it.name] = {
      ms: e.ms,
      easing: e.easing,
      spring: e.spring,
      springLinear: e.spring ? springToLinear(e.spring) : null,
      reduced: it.raw.reduced ?? (out.reduced ? out.reduced.default : null),
      properties: it.raw.properties ?? null,
      interruptible: it.raw.interruptible ?? null,
      refs: { duration: slot('duration'), easing: slot('easing'), spring: slot('spring') },
    };
  }
  return out;
}

export function toCss(model, fm) {
  const r = resolveAll(model, fm);
  const base = [];
  const reduced = [];
  const reducedDur = r.reduced && r.reduced.durationMs !== null ? r.reduced.durationMs : 100;
  for (const [n, ms] of Object.entries(r.durations)) base.push(`  --motion-duration-${n}: ${css(ms)};`);
  for (const [n, ms] of Object.entries(r.timeConstants)) base.push(`  --motion-time-${n}: ${css(ms)};`);
  for (const [n, e] of Object.entries(r.easings)) base.push(`  --motion-ease-${n}: ${easingCss(e)};`);
  for (const [n, s] of Object.entries(r.springs)) {
    if (s.linear) {
      base.push(`  --motion-spring-${n}: ${s.linear};`);
      base.push(`  --motion-spring-${n}-duration: ${css(s.settleMs)};`);
    }
  }
  for (const [n, l] of Object.entries(r.loops)) {
    if (l.periodMs !== null) base.push(`  --motion-loop-${n}-period: ${css(l.periodMs)};`);
    if (l.easing) base.push(`  --motion-loop-${n}-easing: ${easingCss(l.easing)};`);
    if (l.reduced) base.push(`  --motion-loop-${n}-reduced: ${l.reduced};`);
  }
  for (const [n, i] of Object.entries(r.intents)) {
    if (i.ms !== null) base.push(`  --motion-intent-${n}-duration: ${css(i.ms)};`);
    const curve = i.springLinear && i.springLinear.css ? i.springLinear.css : i.easing ? easingCss(i.easing) : null;
    if (curve) base.push(`  --motion-intent-${n}-easing: ${curve};`);
    if (i.reduced !== null) base.push(`  --motion-intent-${n}-reduced: ${i.reduced};`);
    const p = parseReduced(i.reduced);
    if (p.kind === 'duration') reduced.push(`  --motion-intent-${n}-duration: ${css(p.ms)};`);
    else if (p.kind === 'keyword') {
      if (p.word === 'instant') reduced.push(`  --motion-intent-${n}-duration: 0ms;`);
      else if (p.word === 'fade') reduced.push(`  --motion-intent-${n}-duration: ${css(reducedDur)};`);
      else if (p.word === 'ease') reduced.push(`  --motion-intent-${n}-easing: ${easeOut};`);
    }
  }
  const head = '/* Generated by design-md-motion. Reduced-motion overrides apply "instant", "fade" and "ease".\n   "static" and "essential" cannot be expressed in a custom property; read the -reduced value. */';
  const parts = [head, ':root {', ...base, '}'];
  if (reduced.length) parts.push('', '@media (prefers-reduced-motion: reduce) {', '  :root {', ...reduced.map((l) => `  ${l}`), '  }', '}');
  return parts.join('\n') + '\n';
}

export function toDtcg(model, fm) {
  const r = resolveAll(model, fm);
  const dur = (ms) => (ms % 1000 === 0 && ms !== 0 ? { value: ms / 1000, unit: 's' } : { value: ms, unit: 'ms' });
  const tokens = { duration: {}, easing: {}, spring: {}, loop: {}, intent: {} };
  for (const [n, ms] of Object.entries(r.durations)) tokens.duration[n] = { $type: 'duration', $value: { value: ms, unit: 'ms' } };
  for (const [n, ms] of Object.entries(r.timeConstants)) (tokens['time-constants'] ??= {})[n] = { $type: 'duration', $value: { value: ms, unit: 'ms' } };
  for (const [n, e] of Object.entries(r.easings)) {
    if (e.bezier) tokens.easing[n] = { $type: 'cubicBezier', $value: e.bezier };
    else tokens.easing[n] = { $type: 'design-md-motion.easing', $value: e.css, $description: 'Not representable as a DTCG cubicBezier' };
  }
  for (const [n, s] of Object.entries(r.springs)) {
    tokens.spring[n] = {
      $type: 'design-md-motion.spring',
      $value: { stiffness: s.stiffness, damping: s.damping, mass: s.mass },
      $extensions: { 'design-md-motion': { settleMs: s.settleMs, dampingRatio: Math.round(s.derived.dampingRatio * 1000) / 1000, linear: s.linear } },
    };
  }
  for (const [n, l] of Object.entries(r.loops)) {
    tokens.loop[n] = {
      $type: 'design-md-motion.loop',
      $value: {
        period: l.periodRef ? `{motion.${l.periodRef}}` : l.periodMs === null ? null : dur(l.periodMs),
        easing: l.easingRef ? `{motion.easing.${l.easingRef}}` : l.easing ? l.easing.css : null,
        reduced: l.reduced,
      },
    };
  }
  for (const [n, i] of Object.entries(r.intents)) {
    const v = {};
    if (i.refs.duration) v.duration = `{motion.${i.refs.duration}}`;
    else if (i.ms !== null && !i.refs.spring) v.duration = dur(i.ms);
    if (i.refs.easing) v.easing = `{motion.easing.${i.refs.easing.split('.').pop()}}`;
    else if (i.easing) v.easing = i.easing.bezier ?? i.easing.css;
    if (i.refs.spring) v.spring = `{motion.spring.${i.refs.spring.split('.').pop()}}`;
    if (i.reduced !== null) v.reduced = i.reduced;
    if (i.properties) v.properties = i.properties;
    tokens.intent[n] = { $type: 'design-md-motion.intent', $value: v };
  }
  for (const k of Object.keys(tokens)) if (!Object.keys(tokens[k]).length) delete tokens[k];
  const out = { motion: tokens };
  if (r.reduced) out.motion.reduced = { $type: 'design-md-motion.reduced', $value: { default: r.reduced.default, duration: r.reduced.durationMs === null ? null : dur(r.reduced.durationMs) } };
  return JSON.stringify(out, null, 2) + '\n';
}
